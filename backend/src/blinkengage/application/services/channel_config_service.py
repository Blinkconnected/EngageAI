"""Application service for per-company channel configuration. See
``docs/architecture/channels.md`` and
``docs/architecture/channel-integration-spec.md`` (Phase 1: Channel
Experience — credential validation, test connection, health monitoring,
connection logs).
"""

import secrets
from datetime import UTC, datetime
from typing import Any
from uuid import UUID

from blinkengage.core.config import Settings
from blinkengage.core.logging import get_logger
from blinkengage.domain.channels import HealthStatus
from blinkengage.domain.events import DomainEvent, DomainEventPublisher
from blinkengage.domain.exceptions import EntityNotFoundError, InvalidChannelTypeError
from blinkengage.infrastructure.channels.credential_schemas import (
    AUTO_GENERATED_CREDENTIAL_FIELDS,
    validate_channel_credentials,
)
from blinkengage.infrastructure.channels.error_sanitizer import (
    redact_credentials,
    safe_health_check,
)
from blinkengage.infrastructure.channels.factory import ChannelProviderFactory
from blinkengage.infrastructure.channels.registry import ChannelRegistry
from blinkengage.infrastructure.database.models.channel_config import ChannelConfig
from blinkengage.infrastructure.database.models.channel_connection_log import (
    ChannelConnectionLog,
)
from blinkengage.infrastructure.repositories.channel_config_repository import (
    ChannelConfigRepository,
)
from blinkengage.infrastructure.repositories.channel_connection_log_repository import (
    ChannelConnectionLogRepository,
)

logger = get_logger(__name__)


class ChannelConfigService:
    def __init__(
        self,
        *,
        channel_configs: ChannelConfigRepository,
        connection_logs: ChannelConnectionLogRepository,
        provider_factory: ChannelProviderFactory,
        events: DomainEventPublisher,
        settings: Settings,
    ) -> None:
        self._channel_configs = channel_configs
        self._connection_logs = connection_logs
        self._provider_factory = provider_factory
        self._events = events
        self._settings = settings

    async def create(
        self,
        *,
        company_id: UUID,
        channel_type: str,
        display_name: str,
        credentials: dict[str, Any],
        webhook_secret: str | None,
        actor_user_id: UUID | None = None,
    ) -> ChannelConfig:
        if channel_type not in ChannelRegistry.known_channel_types():
            raise InvalidChannelTypeError(channel_type)

        # Auto-generated by default rather than requiring the operator to
        # invent one — see channel-integration-spec.md gap #7. An
        # operator-supplied value (e.g. a provider that requires a
        # specific format) is still respected. Applied before validation
        # so the filled-in value is what actually gets checked/stored.
        auto_field = AUTO_GENERATED_CREDENTIAL_FIELDS.get(channel_type)
        if auto_field and not credentials.get(auto_field):
            credentials = {**credentials, auto_field: secrets.token_urlsafe(24)}
        validate_channel_credentials(channel_type, credentials)

        resolved_webhook_secret = webhook_secret or secrets.token_urlsafe(32)

        channel_config = await self._channel_configs.add(
            ChannelConfig(
                company_id=company_id,
                channel_type=channel_type,
                display_name=display_name,
                credentials=credentials,
                webhook_secret=resolved_webhook_secret,
            )
        )
        await self._log(
            channel_config,
            event_type="created",
            level="info",
            message=f"Channel {display_name!r} ({channel_type}) connected.",
        )
        await self._register_webhook(channel_config)
        await self._events.publish(
            DomainEvent(
                event_type="channel_config.created",
                company_id=company_id,
                aggregate_type="channel_config",
                aggregate_id=channel_config.id,
                actor_user_id=actor_user_id,
                payload={"channel_type": channel_type, "display_name": display_name},
            )
        )
        return channel_config

    async def get(self, *, company_id: UUID, channel_config_id: UUID) -> ChannelConfig:
        channel_config = await self._channel_configs.get_by_id(
            company_id=company_id, channel_config_id=channel_config_id
        )
        if channel_config is None:
            raise EntityNotFoundError("ChannelConfig", channel_config_id)
        return channel_config

    async def list_channel_configs(
        self, *, company_id: UUID, offset: int, limit: int
    ) -> tuple[list[ChannelConfig], int]:
        return await self._channel_configs.list_for_company(
            company_id=company_id, offset=offset, limit=limit
        )

    async def update(
        self,
        *,
        company_id: UUID,
        channel_config_id: UUID,
        display_name: str | None,
        credentials: dict[str, Any] | None,
        webhook_secret: str | None,
        is_active: bool | None,
        actor_user_id: UUID | None = None,
    ) -> ChannelConfig:
        channel_config = await self.get(company_id=company_id, channel_config_id=channel_config_id)
        if credentials is not None:
            validate_channel_credentials(channel_config.channel_type, credentials)
        credentials_changed = credentials is not None or webhook_secret is not None
        if display_name is not None:
            channel_config.display_name = display_name
        if credentials is not None:
            channel_config.credentials = credentials
            await self._log(
                channel_config,
                event_type="credentials_updated",
                level="info",
                message="Credentials were updated (reconnect flow).",
            )
        if webhook_secret is not None:
            channel_config.webhook_secret = webhook_secret
        activation_changed = is_active is not None and is_active != channel_config.is_active
        if activation_changed and is_active is not None:
            channel_config.is_active = is_active
            await self._log(
                channel_config,
                event_type="activated" if is_active else "deactivated",
                level="info",
                message=f"Channel {'activated' if is_active else 'deactivated'}.",
            )

        if channel_config.is_active and (credentials_changed or activation_changed):
            await self._register_webhook(channel_config)
        elif not channel_config.is_active and activation_changed:
            await self._deregister_webhook(channel_config)

        await self._events.publish(
            DomainEvent(
                event_type="channel_config.updated",
                company_id=company_id,
                aggregate_type="channel_config",
                aggregate_id=channel_config.id,
                actor_user_id=actor_user_id,
                payload={
                    "display_name": channel_config.display_name,
                    "is_active": channel_config.is_active,
                },
            )
        )
        return channel_config

    async def delete(
        self, *, company_id: UUID, channel_config_id: UUID, actor_user_id: UUID | None = None
    ) -> None:
        channel_config = await self.get(company_id=company_id, channel_config_id=channel_config_id)
        await self._deregister_webhook(channel_config)
        await self._channel_configs.soft_delete(channel_config)
        await self._events.publish(
            DomainEvent(
                event_type="channel_config.deleted",
                company_id=company_id,
                aggregate_type="channel_config",
                aggregate_id=channel_config.id,
                actor_user_id=actor_user_id,
                payload={"display_name": channel_config.display_name},
            )
        )

    async def test_connection(
        self, *, company_id: UUID, channel_config_id: UUID
    ) -> HealthStatus:
        """Manual "Test Connection" against an already-saved channel — the
        same check the health-monitoring sweep runs periodically, but
        triggered on demand and always logged (an explicit operator
        action, unlike a routine background tick)."""
        channel_config = await self.get(company_id=company_id, channel_config_id=channel_config_id)
        provider = self._provider_factory.build(channel_config)
        status = await safe_health_check(provider, channel_config.credentials)
        self._apply_health_status(channel_config, status)
        await self._log(
            channel_config,
            event_type="test_connection_succeeded" if status.healthy else "test_connection_failed",
            level="info" if status.healthy else "error",
            message=status.detail or ("Connection OK." if status.healthy else "Connection failed."),
        )
        return status

    async def test_connection_ephemeral(
        self,
        *,
        company_id: UUID,
        channel_type: str,
        credentials: dict[str, Any],
        webhook_secret: str | None,
        actor_user_id: UUID | None = None,
    ) -> HealthStatus:
        """Validates + tests credentials the operator has typed into the
        guided setup wizard but not saved yet. Nothing is persisted to
        ``ChannelConnectionLog`` (no ``ChannelConfig`` row exists to
        attach one to) — but this still makes the server originate a real
        outbound connection to an operator-chosen host, so it's audited
        via the general event bus like any other ``channels.manage``
        action, closing the "fully invisible network probe" gap flagged
        in Phase 1's review."""
        if channel_type not in ChannelRegistry.known_channel_types():
            raise InvalidChannelTypeError(channel_type)
        validate_channel_credentials(channel_type, credentials)
        provider = self._provider_factory.build_ephemeral(
            channel_type=channel_type,
            company_id=company_id,
            credentials=credentials,
            webhook_secret=webhook_secret,
        )
        status = await safe_health_check(provider, credentials)
        await self._events.publish(
            DomainEvent(
                event_type="channel_config.test_connection_ephemeral",
                company_id=company_id,
                aggregate_type="channel_config",
                aggregate_id=None,
                actor_user_id=actor_user_id,
                payload={"channel_type": channel_type, "healthy": status.healthy},
            )
        )
        return status


    async def list_connection_logs(
        self, *, company_id: UUID, channel_config_id: UUID, offset: int, limit: int
    ) -> tuple[list[ChannelConnectionLog], int]:
        # Confirms the channel exists (and belongs to this company)
        # before exposing its log history — 404s consistently with every
        # other per-channel sub-resource.
        await self.get(company_id=company_id, channel_config_id=channel_config_id)
        return await self._connection_logs.list_for_channel(
            channel_config_id=channel_config_id, offset=offset, limit=limit
        )

    def _webhook_url(self, channel_config: ChannelConfig) -> str:
        # Same reconstruction as api/v1/endpoints/webhooks.py's
        # _reconstructed_url — settings.public_base_url must be the
        # provider-reachable HTTPS origin in a real deployment.
        return (
            f"{self._settings.public_base_url}{self._settings.api_v1_prefix}"
            f"/webhooks/{channel_config.id}"
        )

    async def _register_webhook(self, channel_config: ChannelConfig) -> None:
        """Best-effort: a provider whose webhook registration call fails
        (e.g. Telegram) must not fail the whole create/update — the
        channel is still saved, and the failure is visible in its
        connection logs (surfaced the same way a failed "Test Connection"
        already is) rather than a raised 500."""
        provider = self._provider_factory.build(channel_config)
        try:
            await provider.configure_webhook(webhook_url=self._webhook_url(channel_config))
        except Exception as exc:
            message = redact_credentials(str(exc), channel_config.credentials)
            logger.warning(
                "channel_webhook_registration_failed",
                channel_config_id=str(channel_config.id),
                channel_type=channel_config.channel_type,
                exc_info=True,
            )
            await self._log(
                channel_config,
                event_type="webhook_registration_failed",
                level="error",
                message=message,
            )

    async def _deregister_webhook(self, channel_config: ChannelConfig) -> None:
        provider = self._provider_factory.build(channel_config)
        try:
            await provider.deregister_webhook()
        except Exception:
            logger.warning(
                "channel_webhook_deregistration_failed",
                channel_config_id=str(channel_config.id),
                channel_type=channel_config.channel_type,
                exc_info=True,
            )

    def _apply_health_status(self, channel_config: ChannelConfig, status: HealthStatus) -> None:
        channel_config.last_health_status = "healthy" if status.healthy else "unhealthy"
        channel_config.last_health_checked_at = datetime.now(UTC)
        channel_config.last_health_detail = status.detail

    async def _log(
        self, channel_config: ChannelConfig, *, event_type: str, level: str, message: str
    ) -> None:
        await self._connection_logs.add(
            ChannelConnectionLog(
                channel_config_id=channel_config.id,
                company_id=channel_config.company_id,
                event_type=event_type,
                level=level,
                message=message,
            )
        )
