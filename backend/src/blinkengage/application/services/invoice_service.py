"""The invoice engine. See ``docs/architecture/billing.md``.

An invoice is generated by **copying** a closed billing period's frozen
snapshot. Nothing here re-aggregates usage records and nothing
re-resolves a price: the numbers were settled when the period closed,
and re-deriving them would be another chance to differ from what the
customer was already told.

Four rules the code enforces rather than documents:

**Issued means immutable.** After issuance an invoice's identity and
money never change. A correction is a *credit note* — a separate
numbered document referencing the invoice — because editing a document
somebody already received leaves two parties holding different versions
of the same number.

**Numbers are gapless and assigned once.** At issuance, from a counter
that participates in the transaction, so a rolled-back issue releases
its number instead of burning it. A draft carries none.

**Every transition is checked against the state machine**
(``domain/invoicing.py``) *and* applied with the current status in the
WHERE clause, so a race loses rather than corrupts.

**Payments are independent.** Money arrives, then it is allocated. One
payment can settle several invoices; an unallocated remainder is simply
a payment with no rows against it.
"""

