@dataclass(frozen=True, slots=True)
class CreditLineInput:
    description: str
    quantity: Decimal
    unit_amount: Decimal
    invoice_line_id: uuid.UUID | None = None


class InvoiceService:
    def __init__(
        self,
        *,
        invoices: InvoiceRepository,
        lines: InvoiceLineRepository,
        credit_notes: CreditNoteRepository,
        payments: PaymentRepository,
        numbers: DocumentNumberRepository,
        periods: BillingPeriodRepository,
        period_lines: UsagePeriodLineRepository,
        companies: InvoiceCompanyLookup,
        events: DomainEventPublisher,
        audit: FinancialAuditRecorder,
        ledger: LedgerService,
    ) -> None:
        self._invoices = invoices
        self._lines = lines
        self._credit_notes = credit_notes
        self._payments = payments
        self._numbers = numbers
        self._periods = periods
        self._period_lines = period_lines
        self._companies = companies
        self._events = events
        self._audit = audit
        self._ledger = ledger

    # --- Generation -------------------------------------------------

    async def generate_for_period(
        self, period_id: uuid.UUID, *, actor: AuditActor | None = None
    ) -> Invoice:
        """Creates a **draft** invoice from a closed period's snapshot.

        Idempotent: a period that already has an invoice returns it
        rather than producing a second bill for the same month — the
        failure mode that charges a customer twice. A unique constraint
        backs that up in case two callers race.

        Only a *closed* period can be invoiced. Billing an open month
        would bill a number that is still moving.
        """
        actor = actor or AuditActor.system_actor()
        period = await self._periods.get_by_id(period_id)
        if period is None:
            raise EntityNotFoundError("BillingPeriod", period_id)
        if period.status is not BillingPeriodStatus.CLOSED:
            raise InvoiceStateError(
                "This billing period is still open. Close it first — invoicing a period "
                "whose usage is still accruing would bill a number that is still moving."
            )

        existing = await self._invoices.for_billing_period(period_id)
        if existing is not None:
            return existing

        snapshot = await self._period_lines.for_period(period_id)
        company = await self._companies.snapshot(period.company_id)
        if company is None:
            raise EntityNotFoundError("Company", period.company_id)
        customer_name, customer_slug = company

        # A copy, never a recomputation. The snapshot already holds the
        # quantity, the price that applied and the subtotal.
        subtotal = to_storage(total([line.subtotal for line in snapshot]))
        invoice = await self._invoices.add(
            Invoice(
                company_id=period.company_id,
                billing_period_id=period_id,
                status=InvoiceStatus.DRAFT,
                customer_name=customer_name,
                customer_slug=customer_slug,
                period_start=period.period_start,
                period_end=period.period_end,
                subtotal_amount=subtotal,
                # Rounded exactly once, here. Every line stays at full
                # precision; only what the customer is asked to pay is
                # rounded to the currency.
                total_amount=to_storage(to_billable_amount(subtotal)),
                currency=period.currency or BILLING_CURRENCY.code,
                amount_paid=zero(),
                amount_credited=zero(),
                due_date=period.due_date.date() if period.due_date else None,
            )
        )
        await self._lines.add_all(
            [
                InvoiceLine(
                    invoice_id=invoice.id,
                    usage_period_line_id=line.id,
                    metric_code=line.metric_code,
                    metric_version=line.metric_version,
                    description=line.metric_display_name,
                    unit=line.unit,
                    quantity=line.quantity,
                    included_quantity=line.included_quantity,
                    billable_quantity=line.billable_quantity,
                    unit_amount=line.unit_amount,
                    currency=line.currency,
                    subtotal=line.subtotal,
                    rate_id=line.rate_id,
                )
                for line in snapshot
            ]
        )
        await self._audit.record(
            event_type=FinancialEventType.INVOICE_CREATED,
            entity_type=FinancialEntityType.INVOICE,
            entity_id=invoice.id,
            company_id=invoice.company_id,
            actor=actor,
            previous_state=None,
            new_state=InvoiceStatus.DRAFT.value,
            amount=invoice.total_amount,
            currency=invoice.currency,
            details={
                "billing_period_id": str(period_id),
                "line_count": len(snapshot),
            },
        )
        return invoice

    # --- Lifecycle --------------------------------------------------

    async def issue(
        self,
        *,
        invoice_id: uuid.UUID,
        actor_user_id: uuid.UUID | None = None,
        actor: AuditActor | None = None,
    ) -> Invoice:
        """Numbers the invoice and freezes it.

        The number is taken inside this transaction, so a failure after
        taking it releases it again — that is what keeps the series
        gapless. The status change is guarded on ``DRAFT``, so two
        concurrent issues cannot both succeed and take two numbers for
        one document.
        """
        invoice = await self._require(invoice_id)
        assert_transition(invoice.status, InvoiceStatus.ISSUED)

        issued_at = datetime.now(UTC)
        year = issued_at.year
        sequence = await self._numbers.next_value(prefix=INVOICE_PREFIX, year=year)
        number = invoice_number(year, sequence)

        won = await self._invoices.transition(
            invoice_id=invoice_id,
            expected=InvoiceStatus.DRAFT,
            target=InvoiceStatus.ISSUED,
            invoice_number=number,
            issued_at=issued_at,
            issued_by_user_id=actor_user_id,
        )
        if not won:
            raise InvoiceStateError(
                "This invoice was issued by another request a moment ago. Reload it."
            )

        await self._audit.record(
            event_type=FinancialEventType.INVOICE_ISSUED,
            entity_type=FinancialEntityType.INVOICE,
            entity_id=invoice_id,
            company_id=invoice.company_id,
            actor=actor or AuditActor(user_id=actor_user_id),
            previous_state=InvoiceStatus.DRAFT.value,
            new_state=InvoiceStatus.ISSUED.value,
            amount=invoice.total_amount,
            currency=invoice.currency,
            details={"invoice_number": number, "due_date": str(invoice.due_date)},
        )
        # Issuance is the moment the money becomes real: a receivable
        # exists and revenue is recognised. A draft posts nothing, which
        # is why this lives here and not in generation.
        if invoice.total_amount > 0:
            await self._ledger.record(
                entry_type=LedgerEntryType.INVOICE_ISSUED,
                company_id=invoice.company_id,
                amount=invoice.total_amount,
                reference_entity="invoice",
                reference_id=invoice_id,
                reference_number=number,
                description=f"Invoice {number} issued to {invoice.customer_name}",
                occurred_at=issued_at,
                currency=invoice.currency,
            )
        await self._publish(
            invoice, "billing.invoice_issued", actor_user_id, {"invoice_number": number}
        )
        return await self._require(invoice_id)

    async def cancel(
        self,
        *,
        invoice_id: uuid.UUID,
        reason: str,
        actor_user_id: uuid.UUID | None = None,
        actor: AuditActor | None = None,
    ) -> Invoice:
        """Withdraws an invoice.

        For a document that should never have existed. A *partly* wrong
        invoice is corrected with a credit note instead — cancelling one
        the customer has already paid against would leave the payment
        allocated to nothing.

        The number stays consumed. Reusing it would mean two different
        documents shared a number, which is precisely what the series
        exists to prevent.
        """
        invoice = await self._require(invoice_id)
        # Captured before the transition: reading `invoice.status` after
        # the UPDATE returns the *new* state, and an audit row claiming a
        # document went from cancelled to cancelled is worse than none.
        previous_state = invoice.status.value
        assert_transition(invoice.status, InvoiceStatus.CANCELLED)
        if invoice.amount_paid > 0:
            raise InvoiceStateError(
                "This invoice has payments allocated to it. Reverse the allocation, or "
                "issue a credit note — cancelling would leave the payment attached to a "
                "withdrawn document."
            )

        won = await self._invoices.transition(
            invoice_id=invoice_id,
            expected=invoice.status,
            target=InvoiceStatus.CANCELLED,
            cancelled_at=datetime.now(UTC),
            cancellation_reason=reason,
        )
        if not won:
            raise InvoiceStateError("This invoice changed state; reload it and try again.")
        await self._audit.record(
            event_type=FinancialEventType.INVOICE_CANCELLED,
            entity_type=FinancialEntityType.INVOICE,
            entity_id=invoice_id,
            company_id=invoice.company_id,
            actor=actor or AuditActor(user_id=actor_user_id),
            previous_state=previous_state,
            new_state=InvoiceStatus.CANCELLED.value,
            amount=invoice.total_amount,
            currency=invoice.currency,
            reason=reason,
            details={"invoice_number": invoice.invoice_number},
        )
        await self._publish(invoice, "billing.invoice_cancelled", actor_user_id, {"reason": reason})
        return await self._require(invoice_id)

    async def mark_overdue(self, *, today: date | None = None) -> list[uuid.UUID]:
        """Moves issued invoices past their due date to ``OVERDUE``.

        A stored state rather than a computed one, so it is filterable
        and does not change meaning depending on which timezone the
        reader evaluates it in. Guarded on ``ISSUED``, so an invoice paid
        in the same instant is not dragged backwards into overdue.
        """
        moment = today or datetime.now(UTC).date()
        moved: list[uuid.UUID] = []
        for invoice in await self._invoices.overdue_candidates(today=moment):
            if await self._invoices.transition(
                invoice_id=invoice.id,
                expected=InvoiceStatus.ISSUED,
                target=InvoiceStatus.OVERDUE,
            ):
                moved.append(invoice.id)
                await self._audit.record(
                    event_type=FinancialEventType.INVOICE_OVERDUE,
                    entity_type=FinancialEntityType.INVOICE,
                    entity_id=invoice.id,
                    company_id=invoice.company_id,
                    # Genuinely nobody: a scheduled sweep moved it. That
                    # is a different answer from "we don't know who".
                    actor=AuditActor.system_actor("Overdue sweep"),
                    previous_state=InvoiceStatus.ISSUED.value,
                    new_state=InvoiceStatus.OVERDUE.value,
                    amount=invoice.total_amount,
                    currency=invoice.currency,
                    details={
                        "invoice_number": invoice.invoice_number,
                        "due_date": str(invoice.due_date),
                    },
                )
                await self._publish(invoice, "billing.invoice_overdue", None, {})
        return moved

    # --- Payments ---------------------------------------------------

    async def record_payment(
        self,
        *,
        company_id: uuid.UUID,
        amount: Decimal,
        received_at: datetime,
        reference: str | None = None,
        note: str | None = None,
        provider: str | None = None,
        provider_reference: str | None = None,
        actor_user_id: uuid.UUID | None = None,
        actor: AuditActor | None = None,
    ) -> Payment:
        """Records money received. Not attached to an invoice.

        A payment is an event in its own right — it may settle several
        invoices, part of one, or none yet. Allocation is a separate
        step, which is what lets a single bank transfer clear three
        invoices and lets an overpayment sit as a credit balance without
        a special case.
        """
        if provider and provider_reference:
            existing = await self._payments.get_by_provider_reference(
                provider=provider, reference=provider_reference
            )
            if existing is not None:
                # A redelivered gateway webhook. Returning the existing
                # payment is the correct response, not an error.
                return existing

        payment = await self._payments.add(
            Payment(
                company_id=company_id,
                amount=to_storage(amount),
                currency=BILLING_CURRENCY.code,
                received_at=received_at,
                provider=provider,
                provider_reference=provider_reference,
                reference=reference,
                note=note,
                recorded_by_user_id=actor_user_id,
            )
        )
        await self._audit.record(
            event_type=FinancialEventType.PAYMENT_RECORDED,
            entity_type=FinancialEntityType.PAYMENT,
            entity_id=payment.id,
            company_id=company_id,
            actor=actor or AuditActor(user_id=actor_user_id),
            previous_state=None,
            new_state="recorded",
            amount=payment.amount,
            currency=payment.currency,
            details={"provider": provider, "reference": reference},
        )
        # Cash in, and a liability: the money is still the customer's
        # until it settles something. Allocation is what discharges it.
        await self._ledger.record(
            entry_type=LedgerEntryType.PAYMENT_RECEIVED,
            company_id=company_id,
            amount=payment.amount,
            reference_entity="payment",
            reference_id=payment.id,
            description=(
                f"Payment received{f' ({reference})' if reference else ''}"
                f"{f' via {provider}' if provider else ''}"
            ),
            occurred_at=received_at,
            currency=payment.currency,
        )
        await self._events.publish(
            DomainEvent(
                event_type="billing.payment_recorded",
                company_id=company_id,
                aggregate_type="payment",
                aggregate_id=payment.id,
                actor_user_id=actor_user_id,
                payload={"amount": str(payment.amount), "currency": payment.currency},
            )
        )
        return payment

    async def allocate(
        self,
        *,
        payment_id: uuid.UUID,
        invoice_id: uuid.UUID,
        amount: Decimal,
        actor_user_id: uuid.UUID | None = None,
        actor: AuditActor | None = None,
    ) -> Invoice:
        """Applies part of a payment to an invoice.

        Two things it refuses, both of which would otherwise show up as
        a balance that cannot be explained: allocating more of a payment
        than was received, and allocating more to an invoice than it
        still owes.
        """
        payment = await self._payments.get_by_id(payment_id)
        if payment is None:
            raise EntityNotFoundError("Payment", payment_id)
        invoice = await self._require(invoice_id)

        if invoice.status not in OPEN_STATES:
            raise InvoiceNotPayableError(
                f"An invoice that is {invoice.status.value} cannot take a payment."
            )
        if invoice.company_id != payment.company_id:
            raise InvoiceNotPayableError(
                "That payment belongs to a different company than this invoice."
            )

        already = await self._payments.allocated_total(payment_id)
        if to_storage(already + amount) > payment.amount:
            raise InvoiceNotPayableError(
                f"Only {payment.amount - already} of this payment is unallocated; "
                f"cannot allocate {amount}."
            )

        outstanding = invoice.total_amount - invoice.amount_paid - invoice.amount_credited
        if to_storage(amount) > outstanding:
            raise InvoiceNotPayableError(
                f"This invoice only has {outstanding} outstanding; cannot allocate {amount}."
            )

        allocation = await self._payments.add_allocation(
            PaymentAllocation(
                payment_id=payment_id, invoice_id=invoice_id, amount=to_storage(amount)
            )
        )
        await self._invoices.apply_payment(invoice_id=invoice_id, amount=to_storage(amount))
        await self._audit.record(
            event_type=FinancialEventType.PAYMENT_ALLOCATED,
            entity_type=FinancialEntityType.PAYMENT_ALLOCATION,
            entity_id=allocation.id,
            company_id=invoice.company_id,
            actor=actor or AuditActor(user_id=actor_user_id),
            previous_state=None,
            new_state="allocated",
            amount=to_storage(amount),
            currency=invoice.currency,
            details={
                "payment_id": str(payment_id),
                "invoice_id": str(invoice_id),
                "invoice_number": invoice.invoice_number,
            },
        )
        # Discharges the liability against the receivable. Neither cash
        # nor revenue moves here — which is exactly why receiving and
        # allocating are separate operations.
        await self._ledger.record(
            entry_type=LedgerEntryType.PAYMENT_ALLOCATED,
            company_id=invoice.company_id,
            amount=to_storage(amount),
            reference_entity="payment_allocation",
            reference_id=allocation.id,
            reference_number=invoice.invoice_number,
            description=(
                f"Payment applied to {invoice.invoice_number or 'an invoice'}"
            ),
            currency=invoice.currency,
        )
        await self._settle_if_covered(invoice_id, actor_user_id)
        return await self._require(invoice_id)

    async def _settle_if_covered(
        self, invoice_id: uuid.UUID, actor_user_id: uuid.UUID | None
    ) -> None:
        """Marks an invoice paid once payments plus credits cover it.

        Credits count towards settlement: an invoice for 100 with a 40
        credit note is settled by 60. Treating only payments as
        settlement would leave a permanently outstanding balance nobody
        can clear.
        """
        invoice = await self._require(invoice_id)
        if invoice.status not in OPEN_STATES:
            return
        covered = invoice.amount_paid + invoice.amount_credited
        if covered < invoice.total_amount:
            return
        # Same reason as in `cancel`: capture it before the UPDATE.
        previous_state = invoice.status.value
        await self._invoices.transition(
            invoice_id=invoice_id,
            expected=invoice.status,
            target=InvoiceStatus.PAID,
            paid_at=datetime.now(UTC),
        )
        await self._audit.record(
            event_type=FinancialEventType.INVOICE_PAID,
            entity_type=FinancialEntityType.INVOICE,
            entity_id=invoice_id,
            company_id=invoice.company_id,
            actor=AuditActor(user_id=actor_user_id),
            previous_state=previous_state,
            new_state=InvoiceStatus.PAID.value,
            amount=invoice.total_amount,
            currency=invoice.currency,
            details={
                "invoice_number": invoice.invoice_number,
                "amount_paid": str(invoice.amount_paid),
                "amount_credited": str(invoice.amount_credited),
            },
        )
        await self._publish(invoice, "billing.invoice_paid", actor_user_id, {})

    # --- Credit notes -----------------------------------------------

    async def issue_credit_note(
        self,
        *,
        invoice_id: uuid.UUID,
        lines: list[CreditLineInput],
        reason: str,
        actor_user_id: uuid.UUID | None = None,
        actor: AuditActor | None = None,
    ) -> CreditNote:
        """Corrects an issued invoice without touching it.

        This is the only way to change what a customer owes after
        issuance. The invoice keeps saying exactly what it said; the
        credit note says what was given back, and both documents exist
        for anybody reconciling them later.
        """
        invoice = await self._require(invoice_id)
        if not is_frozen(invoice.status):
            raise InvoiceStateError(
                "This invoice is still a draft — change the draft rather than crediting it. "
                "Credit notes exist to correct documents that have already been issued."
            )
        if invoice.status is InvoiceStatus.CANCELLED:
            raise InvoiceStateError("This invoice was cancelled, so there is nothing to credit.")
        if not lines:
            raise InvoiceStateError("A credit note must credit at least one line.")

        subtotals = [to_storage(line.quantity * line.unit_amount) for line in lines]
        subtotal = to_storage(total(subtotals))
        if subtotal <= 0:
            raise InvoiceStateError("A credit note must be for a positive amount.")

        already = await self._credit_notes.credited_total(invoice_id)
        if to_storage(already + subtotal) > invoice.total_amount:
            raise InvoiceStateError(
                f"Crediting {subtotal} would exceed the invoice total "
                f"({invoice.total_amount}, of which {already} is already credited)."
            )

        issued_at = datetime.now(UTC)
        sequence = await self._numbers.next_value(prefix=CREDIT_NOTE_PREFIX, year=issued_at.year)
        note = await self._credit_notes.add(
            CreditNote(
                company_id=invoice.company_id,
                invoice_id=invoice_id,
                credit_note_number=credit_note_number(issued_at.year, sequence),
                customer_name=invoice.customer_name,
                subtotal_amount=subtotal,
                total_amount=to_storage(to_billable_amount(subtotal)),
                currency=invoice.currency,
                reason=reason,
                issued_at=issued_at,
                issued_by_user_id=actor_user_id,
            ),
            [
                CreditNoteLine(
                    credit_note_id=uuid.uuid4(),  # replaced by the repository
                    invoice_line_id=line.invoice_line_id,
                    description=line.description,
                    quantity=to_storage(line.quantity),
                    unit_amount=to_storage(line.unit_amount),
                    currency=invoice.currency,
                    subtotal=to_storage(line.quantity * line.unit_amount),
                )
                for line in lines
            ],
        )
        await self._invoices.apply_credit(invoice_id=invoice_id, amount=note.total_amount)
        await self._audit.record(
            event_type=FinancialEventType.CREDIT_NOTE_ISSUED,
            entity_type=FinancialEntityType.CREDIT_NOTE,
            entity_id=note.id,
            company_id=invoice.company_id,
            actor=actor or AuditActor(user_id=actor_user_id),
            previous_state=None,
            new_state="issued",
            amount=note.total_amount,
            currency=note.currency,
            reason=reason,
            details={
                "credit_note_number": note.credit_note_number,
                "invoice_id": str(invoice_id),
                "invoice_number": invoice.invoice_number,
            },
        )
        # Reduces what they owe at the cost of revenue. Contra-revenue,
        # not a negative posting to REVENUE: "what did we bill" and "what
        # did we give back" have to stay separately answerable.
        await self._ledger.record(
            entry_type=LedgerEntryType.CREDIT_NOTE_ISSUED,
            company_id=invoice.company_id,
            amount=note.total_amount,
            reference_entity="credit_note",
            reference_id=note.id,
            reference_number=note.credit_note_number,
            description=(
                f"Credit note {note.credit_note_number} against "
                f"{invoice.invoice_number or 'an invoice'}: {reason}"
            ),
            currency=note.currency,
        )
        await self._settle_if_covered(invoice_id, actor_user_id)
        await self._events.publish(
            DomainEvent(
                event_type="billing.credit_note_issued",
                company_id=invoice.company_id,
                aggregate_type="credit_note",
                aggregate_id=note.id,
                actor_user_id=actor_user_id,
                payload={
                    "credit_note_number": note.credit_note_number,
                    "invoice_number": invoice.invoice_number,
                    "amount": str(note.total_amount),
                    "reason": reason,
                },
            )
        )
        return note

    # --- Reads ------------------------------------------------------

    async def get(self, invoice_id: uuid.UUID) -> Invoice:
        return await self._require(invoice_id)

    async def lines_for(self, invoice_id: uuid.UUID) -> list[InvoiceLine]:
        return await self._lines.for_invoice(invoice_id)

    async def credit_notes_for(self, invoice_id: uuid.UUID) -> list[CreditNote]:
        return await self._credit_notes.for_invoice(invoice_id)

    async def list_for_company(
        self, company_id: uuid.UUID, *, status: InvoiceStatus | None = None
    ) -> list[Invoice]:
        return await self._invoices.list_for_company(company_id, status=status)

    async def payments_for_company(self, company_id: uuid.UUID) -> list[Payment]:
        return await self._payments.list_for_company(company_id)

    # --- Internals --------------------------------------------------

    async def _require(self, invoice_id: uuid.UUID) -> Invoice:
        invoice = await self._invoices.get_by_id(invoice_id)
        if invoice is None:
            raise EntityNotFoundError("Invoice", invoice_id)
        return invoice

    async def _publish(
        self,
        invoice: Invoice,
        event_type: str,
        actor_user_id: uuid.UUID | None,
        extra: dict[str, object],
    ) -> None:
        await self._events.publish(
            DomainEvent(
                event_type=event_type,
                company_id=invoice.company_id,
                aggregate_type="invoice",
                aggregate_id=invoice.id,
                actor_user_id=actor_user_id,
                payload={
                    "invoice_number": invoice.invoice_number,
                    "total_amount": str(invoice.total_amount),
                    "currency": invoice.currency,
                    **extra,
                },
            )
        )


