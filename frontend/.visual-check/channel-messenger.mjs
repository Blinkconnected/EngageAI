import { chromium } from 'playwright'
const b = await chromium.launch()
const p = await b.newPage({ viewport: { width: 1500, height: 1000 }, ignoreHTTPSErrors: true })
await p.goto('https://localhost/login', { waitUntil: 'networkidle' })
await p.fill('input[type="email"]', 'verify-check-8516@blinkconnected.com')
await p.fill('input[type="password"]', 'correct-horse-battery-9')
await p.click('button[type="submit"]')
await p.waitForTimeout(4500)
await p.goto('https://localhost/channels', { waitUntil: 'networkidle' })
await p.waitForTimeout(1200)
await p.click('button:has-text("Connect channel")')
await p.waitForTimeout(800)
await p.click('div.MuiSelect-select')
await p.waitForTimeout(400)
const opts = await p.$$('[role="option"]')
console.log('types:', await Promise.all(opts.map(o => o.textContent())))
for (const o of opts) { if (/messenger/i.test((await o.textContent()) || '')) { await o.click(); break } }
await p.waitForTimeout(900)
const labels = await p.$$eval('label', els => els.map(e => e.textContent?.trim()).filter(Boolean))
console.log('Messenger fields:', labels)
const body = await p.textContent('body')
console.log('says App Secret:', /App Secret/.test(body))
console.log('explains where:', /Settings/.test(body))
console.log('still raw JSON?:', /JSON/i.test(body))
await p.screenshot({ path: '.visual-check/channel-messenger.png', fullPage: false })
await b.close()
